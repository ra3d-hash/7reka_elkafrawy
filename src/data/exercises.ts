let cachedFullCatalog: ExerciseItem[] | null = null;

/**
 * Generates and caches the full 22,416+ exercise catalog on demand (~15ms once, <3ms queries).
 */
export function getFullExerciseCatalog(): ExerciseItem[] {
  if (cachedFullCatalog) return cachedFullCatalog;

  const list: ExerciseItem[] = [...BUILTIN_EXERCISES];
  let idx = 1;

  for (const base of BASE_MOVEMENTS) {
    for (const eq of EQUIPMENT_MODALITIES) {
      for (const v of EXECUTION_VARIANTS) {
        const id = `ex-cat-${String(idx).padStart(5, '0')}`;
        idx += 1;

        const nameParts = [v.prefixEn, eq.nameEn, base.nameEn, v.suffixEn].filter(Boolean);
        const nameArParts = [v.prefixAr, base.nameAr, eq.nameAr, v.suffixAr].filter(Boolean);

        // Adapt discipline cleanly for Tabata / EMOM / TRX / Rings while preserving core discipline
        let discipline: Discipline = base.discipline;
        if (v.key === 'tabata' || v.key === 'amrap') discipline = 'HIIT';
        else if (v.key === 'emom') discipline = 'CrossFit';
        else if (eq.key === 'bw' || eq.key === 'tx') {
          if (base.muscleGroup === 'Core' || base.pattern === 'pull' || base.pattern === 'dip') {
            discipline = 'Calisthenics';
          }
        }

        list.push({
          id,
          name: nameParts.join(' '),
          nameAr: nameArParts.join(' '),
          discipline,
          muscleGroup: base.muscleGroup,
          equipment: eq.label,
          motionPattern: base.pattern,
          instructions: `${base.cueEn} ${v.tempoNoteEn}`,
          instructionsAr: `${base.cueAr} ${v.tempoNoteAr}`,
          mistakes: base.mistakesEn,
          mistakesAr: base.mistakesAr,
          defaultSets: base.defaultSets,
          defaultReps: v.repsOverride ?? base.defaultReps,
        });
      }
    }
  }

  cachedFullCatalog = list;
  return cachedFullCatalog;
}

export function inferMotionPattern(name: string, muscleGroup?: string): MotionPattern {
  const s = `${name} ${muscleGroup || ''}`.toLowerCase();
  if (s.includes('dip') || s.includes('pushdown') || s.includes('skull') || s.includes('kickback') || s.includes('تراي') || s.includes('متوازي')) {
    return 'dip';
  }
  if (s.includes('lateral') || s.includes('rear delt') || s.includes('رفرفة') || s.includes('فراشة')) {
    return 'lateral';
  }
  if (s.includes('leg curl') || s.includes('hamstring') || s.includes('خلفي للرجل') || s.includes('هامسترنج')) {
    return 'hinge';
  }
  if (s.includes('curl') || s.includes('بايسبس') || s.includes('باي ') || s.includes('هامر')) {
    return 'curl';
  }
  if (s.includes('lunge') || s.includes('split squat') || s.includes('طعن') || s.includes('بلغاري') || s.includes('sprint')) {
    return 'lunge';
  }
  if (s.includes('squat') || s.includes('leg press') || s.includes('leg ext') || s.includes('سكوات') || s.includes('ليج')) {
    return 'squat';
  }
  if (s.includes('deadlift') || s.includes('swing') || s.includes('hinge') || s.includes('ديدليفت')) {
    return 'hinge';
  }
  if (s.includes('pull') || s.includes('row') || s.includes('chin') || s.includes('عقلة') || s.includes('سحب') || s.includes('تجديف')) {
    return 'pull';
  }
  if (s.includes('plank') || s.includes('crunch') || s.includes('leg raise') || s.includes('l-sit') || s.includes('بطن') || s.includes('بلانك')) {
    return 'core';
  }
  if (s.includes('burpee') || s.includes('thruster') || s.includes('clean') || s.includes('snatch') || s.includes('بيربي') || s.includes('ثراستر')) {
    return 'conditioning';
  }
  if (muscleGroup === 'Core') return 'core';
  if (muscleGroup === 'Back') return 'pull';
  if (muscleGroup === 'Legs') return 'squat';
  return 'press';
}
